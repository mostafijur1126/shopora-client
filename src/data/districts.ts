export const isDhakaDistrict = (districtName: string): boolean => {
  if (!districtName) return false;
  const lower = districtName.toLowerCase().trim();
  return lower === 'dhaka' || lower === 'ঢাকা' || lower.includes('dhaka') || lower.includes('ঢাকা');
};

export const getDeliveryFeeForDistrict = (districtName: string): number => {
  return isDhakaDistrict(districtName) ? 60 : 120;
};
